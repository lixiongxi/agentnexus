/** 生成 bot 回复；未配置规则的 agent 返回 null（不自动应答） */
export function botReply(toAgent: string, fromAgent: string, text: string): string | null {
  const rules = KB[toAgent];
  if (!rules) return null;
  const hit = rules.find(x => x.k.some(k => text.toLowerCase().includes(k)));
  if (hit) return hit.r;
  return FALLBACKS[Math.floor(Math.random() * FALLBACKS.length)];
}
